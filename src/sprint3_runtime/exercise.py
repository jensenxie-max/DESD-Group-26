"""Prevent two local demonstration harnesses from consuming each other's jobs."""
from contextlib import contextmanager
import os
from pathlib import Path


@contextmanager
def exclusive_exercise():
    work = Path(__file__).resolve().parents[2] / "work"
    work.mkdir(exist_ok=True)
    with (work / "sprint3-exercise.lock").open("a+b") as handle:
        handle.seek(0, os.SEEK_END)
        if handle.tell() == 0:
            handle.write(b"0")
            handle.flush()
        handle.seek(0)
        try:
            if os.name == "nt":
                import msvcrt
                msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl
                fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            raise RuntimeError("Another Sprint 3 validation or walkthrough is running. Finish it before starting a second exercise.") from None
        try:
            yield
        finally:
            handle.seek(0)
            if os.name == "nt":
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(handle, fcntl.LOCK_UN)
